import json, glob, os
d = os.path.expanduser('~/what-if/what-if-studio/src')
ids = []
for f in sorted(glob.glob(d + '/episodes/*/episode.json')):
    try:
        e = json.load(open(f))
        if e.get('format') == 'short': ids.append(e['id'])
    except Exception as x:
        print('skip', f, x)
open(d + '/shorts.ts', 'w').write('// generated by wid check\nexport const SHORT_IDS: string[] = %s;\n' % json.dumps(ids))
print('shorts:', ids)
